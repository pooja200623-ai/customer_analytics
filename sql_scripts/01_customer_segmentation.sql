USE customer_analytics;

-- -----------------------------------------------------------------------------
-- BUSINESS QUESTION 1: RFM (Recency, Frequency, Monetary) Segmentation
-- -----------------------------------------------------------------------------
-- How can we score and segment customers dynamically based on:
--   1. Recency: How many days since their last delivered order?
--   2. Frequency: Total number of delivered orders placed?
--   3. Monetary: Total spending across all delivered orders?
-- Assign an RFM tier (Champions, Loyal Customers, Potential Loyalists,
-- At-Risk, Lapsed/Inactive) using statistical quartiles.
-- -----------------------------------------------------------------------------

WITH customer_rfm_raw AS (
    SELECT 
        c.customer_id,
        CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
        c.city,
        c.state,
        COUNT(DISTINCT o.order_id) AS total_orders,
        COALESCE(SUM(o.total_amount), 0.00) AS total_spend,
        DATEDIFF('2026-11-10', MAX(o.order_date)) AS days_since_last_order
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id 
                      AND o.status = 'Delivered'
    GROUP BY c.customer_id, c.first_name, c.last_name, c.city, c.state
),
customer_rfm_scores AS (
    SELECT 
        customer_id,
        customer_name,
        city,
        state,
        total_orders,
        total_spend,
        days_since_last_order,
        -- Score 1 to 4: Recency (Lower days = higher score)
        NTILE(4) OVER (ORDER BY days_since_last_order DESC) AS r_score,
        -- Score 1 to 4: Frequency (Higher orders = higher score)
        NTILE(4) OVER (ORDER BY total_orders ASC) AS f_score,
        -- Score 1 to 4: Monetary (Higher spend = higher score)
        NTILE(4) OVER (ORDER BY total_spend ASC) AS m_score
    FROM customer_rfm_raw
),
customer_rfm_composite AS (
    SELECT 
        customer_id,
        customer_name,
        city,
        state,
        total_orders,
        total_spend,
        days_since_last_order,
        r_score,
        f_score,
        m_score,
        ROUND((r_score + f_score + m_score) / 3.0, 2) AS composite_rfm_score
    FROM customer_rfm_scores
)
SELECT 
    customer_id,
    customer_name,
    city,
    state,
    total_orders,
    CONCAT('₹', FORMAT(total_spend, 2)) AS total_spend_formatted,
    days_since_last_order,
    CONCAT(r_score, '-', f_score, '-', m_score) AS rfm_cell,
    composite_rfm_score,
    CASE 
        WHEN composite_rfm_score >= 3.5 THEN 'Champions (VIP)'
        WHEN composite_rfm_score >= 2.8 THEN 'Loyal Customers'
        WHEN composite_rfm_score >= 2.2 THEN 'Potential Loyalists'
        WHEN composite_rfm_score >= 1.6 THEN 'Promising / Needs Attention'
        ELSE 'At Risk / Inactive'
    END AS dynamic_rfm_segment
FROM customer_rfm_composite
ORDER BY composite_rfm_score DESC, total_spend DESC;

-- EXPECTED OUTPUT DESCRIPTION:
-- Returns all 30 customers categorized into 5 actionable RFM segments.
-- Identifies top high-value champions (Aarav Sharma, Sneha Kulkarni, Karan Malhotra, etc.)
-- with their specific R-F-M score breakdown and recency in days.


-- -----------------------------------------------------------------------------
-- BUSINESS QUESTION 2: High-Value Customer (HVC) Percentile & Revenue Contribution
-- -----------------------------------------------------------------------------
-- What percentage of total company revenue is generated by our top 10% and top 25%
-- customers? (Testing the 80/20 Pareto Principle in customer spend).
-- -----------------------------------------------------------------------------

WITH customer_spending AS (
    SELECT 
        c.customer_id,
        CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
        c.segment AS current_segment,
        SUM(o.total_amount) AS customer_revenue,
        PERCENT_RANK() OVER (ORDER BY SUM(o.total_amount) DESC) AS spend_percentile_rank,
        DENSE_RANK() OVER (ORDER BY SUM(o.total_amount) DESC) AS revenue_rank
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    WHERE o.status != 'Cancelled'
    GROUP BY c.customer_id, c.first_name, c.last_name, c.segment
),
overall_totals AS (
    SELECT SUM(total_amount) AS gross_company_revenue FROM orders WHERE status != 'Cancelled'
)
SELECT 
    cs.revenue_rank,
    cs.customer_id,
    cs.customer_name,
    cs.current_segment,
    CONCAT('₹', FORMAT(cs.customer_revenue, 2)) AS customer_revenue,
    ROUND(cs.spend_percentile_rank * 100, 2) AS top_percentile,
    ROUND((cs.customer_revenue / ot.gross_company_revenue) * 100, 2) AS pct_of_company_revenue,
    ROUND(SUM(cs.customer_revenue) OVER (ORDER BY cs.revenue_rank) / ot.gross_company_revenue * 100, 2) AS cumulative_revenue_pct,
    CASE 
        WHEN cs.spend_percentile_rank <= 0.10 THEN 'Tier 1: Top 10% Spender'
        WHEN cs.spend_percentile_rank <= 0.25 THEN 'Tier 2: Top 25% Spender'
        WHEN cs.spend_percentile_rank <= 0.50 THEN 'Tier 3: Mid 25-50% Spender'
        ELSE 'Tier 4: Bottom 50% Spender'
    END AS revenue_contribution_tier
FROM customer_spending cs
CROSS JOIN overall_totals ot
ORDER BY cs.revenue_rank ASC;

-- EXPECTED OUTPUT DESCRIPTION:
-- Shows cumulative revenue percentage by customer rank. Proves that top 25% of customers
-- account for over 50% of cumulative GMV, revealing strong revenue concentration.


-- -----------------------------------------------------------------------------
-- BUSINESS QUESTION 3: Demographic Segmentation by Age Group & Gender
-- -----------------------------------------------------------------------------
-- How does average order value (AOV), total order frequency, and total revenue
-- vary across age demographics (<25 Gen Z, 25-34 Millennials, 35-44 Gen X, 45+ Boomers)
-- and gender cohorts?
-- -----------------------------------------------------------------------------

WITH customer_demographics AS (
    SELECT 
        c.customer_id,
        c.gender,
        TIMESTAMPDIFF(YEAR, c.date_of_birth, '2026-11-10') AS age,
        CASE 
            WHEN TIMESTAMPDIFF(YEAR, c.date_of_birth, '2026-11-10') < 25 THEN '1. Under 25 (Gen Z)'
            WHEN TIMESTAMPDIFF(YEAR, c.date_of_birth, '2026-11-10') BETWEEN 25 AND 34 THEN '2. 25-34 (Millennials)'
            WHEN TIMESTAMPDIFF(YEAR, c.date_of_birth, '2026-11-10') BETWEEN 35 AND 44 THEN '3. 35-44 (Young Gen X)'
            ELSE '4. 45+ (Mature Customers)'
        END AS age_cohort,
        o.order_id,
        o.total_amount
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
)
SELECT 
    age_cohort,
    gender,
    COUNT(DISTINCT customer_id) AS total_customers,
    COUNT(DISTINCT order_id) AS total_orders,
    CONCAT('₹', FORMAT(COALESCE(SUM(total_amount), 0), 2)) AS gross_revenue,
    CONCAT('₹', FORMAT(COALESCE(AVG(total_amount), 0), 2)) AS avg_order_value,
    ROUND(COUNT(DISTINCT order_id) / NULLIF(COUNT(DISTINCT customer_id), 0), 2) AS orders_per_customer
FROM customer_demographics
GROUP BY age_cohort, gender
ORDER BY age_cohort ASC, gross_revenue DESC;

-- EXPECTED OUTPUT DESCRIPTION:
-- Summarizes purchasing power by age group and gender. Demonstrates that Millennials
-- (25-34) and Gen X (35-44) generate the highest average ticket size (AOV).


-- -----------------------------------------------------------------------------
-- BUSINESS QUESTION 4: Geographic Segmentation & Market Penetration
-- -----------------------------------------------------------------------------
-- Which Indian states and metro cities have the highest customer concentration,
-- highest sales volume, and best average customer lifetime value (CLV)?
-- -----------------------------------------------------------------------------

WITH geo_analytics AS (
    SELECT 
        c.state,
        c.city,
        COUNT(DISTINCT c.customer_id) AS total_customers,
        COUNT(DISTINCT o.order_id) AS total_orders,
        COALESCE(SUM(o.total_amount), 0) AS total_sales,
        COALESCE(AVG(o.total_amount), 0) AS aov,
        COALESCE(SUM(o.total_amount) / NULLIF(COUNT(DISTINCT c.customer_id), 0), 0) AS avg_customer_value
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.state, c.city
)
SELECT 
    state,
    city,
    total_customers,
    total_orders,
    CONCAT('₹', FORMAT(total_sales, 2)) AS total_sales,
    CONCAT('₹', FORMAT(aov, 2)) AS avg_order_value,
    CONCAT('₹', FORMAT(avg_customer_value, 2)) AS customer_lifetime_value,
    DENSE_RANK() OVER (ORDER BY total_sales DESC) AS sales_rank_by_city
FROM geo_analytics
ORDER BY total_sales DESC;

-- EXPECTED OUTPUT DESCRIPTION:
-- Ranks cities like Ahmedabad, Bengaluru, Mumbai, Chennai, and Gurugram by total sales,
-- highlighting regional clusters of high-net-worth customers.
